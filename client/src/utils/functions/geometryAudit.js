/**
 * Geometry audit utilities.
 *
 * Pure, side-effect free re-implementations of the geometric rules used by
 * Clipping.jsx (plane negation), clippingObject.js (stencil groups / colored
 * caps) and offsetObject.js (ASCII STL parse + vertex merge + offset).
 *
 * Constraints:
 *  - no dependency on three, window, document or the file system
 *  - every returned value is JSON serializable (plain objects, arrays,
 *    numbers, strings, booleans, null)
 *  - existing modules and their exported signatures are never touched
 */

export const CLIPPING_AUDIT_TYPE = "clipping-audit";
export const OFFSET_AUDIT_TYPE = "offset-audit";

export const POSITION_EPSILON = 1e-9;
export const OFFSET_EPSILON = 1e-6;

/* ------------------------------------------------------------------ */
/* small vector helpers (plain {x,y,z} / arrays, never three objects) */
/* ------------------------------------------------------------------ */

// JSON.stringify turns -0 into 0, so every numeric output is normalized to keep
// the report stable across a JSON round trip.
const nz = (value) => (Object.is(value, -0) ? 0 : value);
const nzArray = (values) => values.map((value) => nz(value));

const toVec3 = (value) => {
  if (value === undefined || value === null) {
    return { x: 0, y: 0, z: 0 };
  }
  if (Array.isArray(value)) {
    return { x: nz(value[0] ?? 0), y: nz(value[1] ?? 0), z: nz(value[2] ?? 0) };
  }
  return { x: nz(value.x ?? 0), y: nz(value.y ?? 0), z: nz(value.z ?? 0) };
};

const add3 = (a, b) => ({ x: nz(a.x + b.x), y: nz(a.y + b.y), z: nz(a.z + b.z) });
const scale3 = (a, scalar) => ({ x: nz(a.x * scalar), y: nz(a.y * scalar), z: nz(a.z * scalar) });
const dot3 = (a, b) => nz(a.x * b.x + a.y * b.y + a.z * b.z);
const negate3 = (a) => ({ x: nz(-a.x), y: nz(-a.y), z: nz(-a.z) });
const sub3 = (a, b) => ({ x: nz(a.x - b.x), y: nz(a.y - b.y), z: nz(a.z - b.z) });
const length3 = (a) => nz(Math.sqrt(dot3(a, a)));

const approxEqual3 = (a, b, epsilon) => {
  const delta = sub3(toVec3(a), toVec3(b));
  return Math.abs(delta.x) <= epsilon && Math.abs(delta.y) <= epsilon && Math.abs(delta.z) <= epsilon;
};

const check = (name, passed, reason) => ({ name, passed: Boolean(passed), reason: passed ? "" : reason });

/* ------------------------------------------------------------------ */
/* entry 1: clipping snapshot audit                                    */
/* ------------------------------------------------------------------ */

/**
 * Audits the clipping geometry that Clipping.jsx / clippingObject.js would
 * generate for a scene snapshot, without instantiating any THREE object.
 *
 * @param {Object} snapshot Plain data snapshot
 * @param {Array}  snapshot.planes Each item: { center:{x,y,z}, normal:{x,y,z}, boundingBoxCenter:{x,y,z} }
 *                 - center is the plane object position used as the coplanar point
 *                 - boundingBoxCenter feeds the barycenter computation (getCenterPoint in the source)
 * @param {Array}  snapshot.meshes Each item: { name, color ("#rrggbb"), clips (boolean) }
 * @param {Object} [observed] Optional plain-data extraction of the geometry actually
 *                 generated by three: { meshPlanes: [{ meshName, planeIndex, stencilGroupName,
 *                 stencilRenderOrder, capName, capColor, capRenderOrder, capPosition,
 *                 capOrientation, capClippingPlaneIndexes }] }. When present every check is
 *                 evaluated against the observed values, otherwise against the derived ones.
 * @returns {Object} Structured, JSON-serializable audit report
 */
export const auditClippingSnapshot = (snapshot, observed) => {
  const safeSnapshot = snapshot || {};
  const planesInput = Array.isArray(safeSnapshot.planes) ? safeSnapshot.planes : [];
  const meshesInput = Array.isArray(safeSnapshot.meshes) ? safeSnapshot.meshes : [];
  const observedRecords = (observed && Array.isArray(observed.meshPlanes) && observed.meshPlanes) || [];

  const checks = [];

  // Barycenter of the plane bounding-box centers (Clipping.jsx createPlanesAndNegated)
  const barycenter = planesInput.length
    ? scale3(
        planesInput.reduce((acc, item) => add3(acc, toVec3(item.boundingBoxCenter)), { x: 0, y: 0, z: 0 }),
        1 / planesInput.length,
      )
    : { x: 0, y: 0, z: 0 };

  const planes = planesInput.map((item, index) => {
    const center = toVec3(item.center);
    const inputNormal = toVec3(item.normal);
    const boundingBoxCenter = toVec3(item.boundingBoxCenter ?? item.center);

    // THREE.Plane.setFromNormalAndCoplanarPoint: constant = -normal.dot(point)
    const constant = nz(-dot3(inputNormal, center));
    // THREE.Plane.distanceToPoint: normal.dot(point) + constant
    const barycenterDistance = nz(dot3(inputNormal, barycenter) + constant);
    const negated = barycenterDistance < 0;

    const effectiveNormal = negated ? negate3(inputNormal) : inputNormal;
    const effectiveConstant = nz(negated ? -constant : constant);
    // THREE.Plane.coplanarPoint: target = constant * -normal
    const coplanarPoint = scale3(effectiveNormal, -effectiveConstant);
    // cap.lookAt(position - normal): the cap +z axis ends up pointing along -normal
    const orientation = negate3(effectiveNormal);
    const lookAtTarget = sub3(coplanarPoint, effectiveNormal);

    const negateReason = negated
      ? `Plane ${index} is negated because the barycenter distance is negative (${barycenterDistance} < 0).`
      : `Plane ${index} is kept as-is because the barycenter distance is non-negative (${barycenterDistance} >= 0).`;

    return {
      index,
      center,
      boundingBoxCenter,
      inputNormal,
      constant,
      barycenterDistance,
      negated,
      negateReason,
      effectiveNormal,
      effectiveConstant,
      coplanarPoint,
      capOrientation: orientation,
      lookAtTarget,
    };
  });

  // Per-plane negation rule check
  planes.forEach((plane) => {
    const expectedNegation = plane.barycenterDistance < 0;
    checks.push(
      check(
        `plane-${plane.index}-negation-rule`,
        plane.negated === expectedNegation,
        `Negation flag (${plane.negated}) does not match the distance rule (distance=${plane.barycenterDistance}).`,
      ),
    );
  });

  // Replay addColorToClippedMesh: outer loop over meshes, inner loop over planes,
  // y increments once per participating (mesh, plane) pair.
  const meshPlanes = [];
  let y = 0;
  meshesInput.forEach((mesh) => {
    planes.forEach((plane) => {
      const participates = mesh.clips !== false;
      const baseRecord = {
        meshName: mesh.name,
        meshColor: mesh.color,
        planeIndex: plane.index,
        participates,
      };

      if (!participates) {
        meshPlanes.push({ ...baseRecord, skipped: true, stencilGroup: null, cap: null });
        return;
      }

      const stencilRenderOrder = y;
      const capRenderOrder = y + 0.1;
      const expected = {
        stencilGroupName: `planeStencilGroup${mesh.name}`,
        stencilRenderOrder,
        capName: `Clipping${mesh.name}`,
        capColor: mesh.color,
        capRenderOrder,
        capPosition: plane.coplanarPoint,
        capOrientation: plane.capOrientation,
        capClippingPlaneIndexes: planes.filter((other) => other.index !== plane.index).map((other) => other.index),
      };

      const observedRecord = observedRecords.find((record) => record.meshName === mesh.name && record.planeIndex === plane.index);

      const actualColor = observedRecord && observedRecord.capColor !== undefined ? observedRecord.capColor : expected.capColor;
      const actualStencilOrder =
        observedRecord && observedRecord.stencilRenderOrder !== undefined ? observedRecord.stencilRenderOrder : expected.stencilRenderOrder;
      const actualCapOrder = observedRecord && observedRecord.capRenderOrder !== undefined ? observedRecord.capRenderOrder : expected.capRenderOrder;
      const actualPosition = observedRecord && observedRecord.capPosition ? toVec3(observedRecord.capPosition) : expected.capPosition;
      const actualOrientation = observedRecord && observedRecord.capOrientation ? toVec3(observedRecord.capOrientation) : expected.capOrientation;
      const actualStencilName =
        observedRecord && observedRecord.stencilGroupName !== undefined ? observedRecord.stencilGroupName : expected.stencilGroupName;
      const actualCapName = observedRecord && observedRecord.capName !== undefined ? observedRecord.capName : expected.capName;
      const actualClippingIndexes =
        observedRecord && Array.isArray(observedRecord.capClippingPlaneIndexes)
          ? observedRecord.capClippingPlaneIndexes
          : expected.capClippingPlaneIndexes;

      const label = `mesh-${mesh.name}-plane-${plane.index}`;

      // 1. cap color must equal the mesh material color
      checks.push(
        check(
          `${label}-cap-color-matches-mesh-color`,
          actualColor === mesh.color,
          `Cap color "${actualColor}" does not equal mesh "${mesh.name}" color "${mesh.color}".`,
        ),
      );

      // 2. cap position must equal the (negated) plane coplanar point
      checks.push(
        check(
          `${label}-cap-position-matches-coplanar-point`,
          approxEqual3(actualPosition, plane.coplanarPoint, POSITION_EPSILON),
          `Cap position ${JSON.stringify(actualPosition)} does not match coplanar point ${JSON.stringify(plane.coplanarPoint)}.`,
        ),
      );

      // 3. cap orientation must face along -effectiveNormal (lookAt(position - normal))
      checks.push(
        check(
          `${label}-cap-orientation-matches-negated-normal`,
          approxEqual3(actualOrientation, plane.capOrientation, POSITION_EPSILON),
          `Cap orientation ${JSON.stringify(actualOrientation)} does not match -normal ${JSON.stringify(plane.capOrientation)}.`,
        ),
      );

      // 4. cap clippingPlanes must exclude the plane itself
      const excludesOwn = !actualClippingIndexes.includes(plane.index);
      const hasEveryOtherPlane = planes.filter((other) => other.index !== plane.index).every((other) => actualClippingIndexes.includes(other.index));
      checks.push(
        check(
          `${label}-cap-clipping-planes-exclude-own-plane`,
          excludesOwn && hasEveryOtherPlane,
          `Cap clipping plane indexes [${actualClippingIndexes.join(", ")}] must exclude plane ${plane.index} and keep every other plane.`,
        ),
      );

      // 5. renderOrder: stencil = y, cap = y + 0.1
      checks.push(
        check(
          `${label}-render-order-follows-y-sequence`,
          actualStencilOrder === y && actualCapOrder === y + 0.1,
          `Expected stencil renderOrder ${y} and cap renderOrder ${y + 0.1}, got ${actualStencilOrder} and ${actualCapOrder}.`,
        ),
      );

      meshPlanes.push({
        ...baseRecord,
        skipped: false,
        orderIndex: y,
        stencilGroup: {
          name: actualStencilName,
          expectedName: expected.stencilGroupName,
          renderOrder: actualStencilOrder,
        },
        cap: {
          name: actualCapName,
          expectedName: expected.capName,
          color: actualColor,
          renderOrder: actualCapOrder,
          position: actualPosition,
          orientation: actualOrientation,
          lookAtTarget: plane.lookAtTarget,
          clippingPlaneIndexes: actualClippingIndexes,
          excludesOwnPlane: excludesOwn,
        },
      });

      y += 1;
    });
  });

  // Global sequence check: y must grow strictly by one across participating pairs,
  // every cap sitting exactly 0.1 above its stencil group.
  const activeRecords = meshPlanes.filter((record) => !record.skipped);
  const sequenceOk = activeRecords.every((record, index) => record.orderIndex === index && record.cap.renderOrder === index + 0.1);
  checks.push(
    check(
      "render-order-monotonic-sequence",
      sequenceOk,
      "Render orders do not follow the source sequence stencil y = 0,1,2,... with caps at y + 0.1.",
    ),
  );

  return {
    type: CLIPPING_AUDIT_TYPE,
    input: {
      planeCount: planesInput.length,
      meshCount: meshesInput.length,
      clippingMeshCount: meshesInput.filter((mesh) => mesh.clips !== false).length,
    },
    barycenter,
    planes,
    meshPlanes,
    checks,
  };
};

