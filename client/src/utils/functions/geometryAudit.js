/* entry 2: ASCII STL offset audit                                     */
/* ------------------------------------------------------------------ */

const PATTERN_SOLID = /solid([\s\S]*?)endsolid/g;
const PATTERN_FACE = /facet([\s\S]*?)endfacet/g;
const PATTERN_FLOAT = /[\s]+([+-]?(?:\d*)(?:\.\d*)?(?:[eE][+-]?\d+)?)/.source;
const PATTERN_VERTEX = new RegExp("vertex" + PATTERN_FLOAT + PATTERN_FLOAT + PATTERN_FLOAT, "g");
const PATTERN_NORMAL = new RegExp("normal" + PATTERN_FLOAT + PATTERN_FLOAT + PATTERN_FLOAT, "g");

/**
 * Parses an ASCII STL document following the same regex strategy as
 * offsetObject.parseASCII, but returning plain arrays.
 */
const parseASCIIStl = (data) => {
  const text = typeof data === "string" ? data : "";
  const faces = [];
  let solidResult;
  const solidPattern = new RegExp(PATTERN_SOLID.source, "g");

  while ((solidResult = solidPattern.exec(text)) !== null) {
    const solid = solidResult[0];
    let faceResult;
    const facePattern = new RegExp(PATTERN_FACE.source, "g");

    while ((faceResult = facePattern.exec(solid)) !== null) {
      const chunk = faceResult[0];
      const originalNormal = [];
      const vertices = [];

      let normalResult;
      const normalPattern = new RegExp(PATTERN_NORMAL.source, "g");
      while ((normalResult = normalPattern.exec(chunk)) !== null) {
        originalNormal.push(nz(parseFloat(normalResult[1])), nz(parseFloat(normalResult[2])), nz(parseFloat(normalResult[3])));
      }

      let vertexResult;
      const vertexPattern = new RegExp(PATTERN_VERTEX.source, "g");
      while ((vertexResult = vertexPattern.exec(chunk)) !== null) {
        vertices.push([nz(parseFloat(vertexResult[1])), nz(parseFloat(vertexResult[2])), nz(parseFloat(vertexResult[3]))]);
      }

      faces.push({ originalNormal, vertices });
    }
  }

  return faces;
};

const normalizeOrZero = (vector) => {
  const modul = Math.sqrt(vector[0] * vector[0] + vector[1] * vector[1] + vector[2] * vector[2]);
  if (modul === 0) {
    return { vector: [0, 0, 0], length: 0, degenerate: true };
  }
  return { vector: nzArray([vector[0] / modul, vector[1] / modul, vector[2] / modul]), length: nz(modul), degenerate: false };
};

// offsetObject.calculateNewNormal (cross product of (v2-v1) x (v3-v1))
const calculateFaceNormal = (v1, v2, v3) => {
  const nx = (v2[1] - v1[1]) * (v3[2] - v1[2]) - (v2[2] - v1[2]) * (v3[1] - v1[1]);
  const ny = -((v2[0] - v1[0]) * (v3[2] - v1[2]) - (v2[2] - v1[2]) * (v3[0] - v1[0]));
  const nzValue = (v2[0] - v1[0]) * (v3[1] - v1[1]) - (v2[1] - v1[1]) * (v3[0] - v1[0]);
  return normalizeOrZero([nx, ny, nzValue]).vector;
};

const vertexKey = (vertex) => `${vertex[0]}|${vertex[1]}|${vertex[2]}`;

/**
 * Audits the offset geometry that offsetObject.createOffsetMesh would produce
 * for an ASCII STL document, without instantiating any THREE object.
 *
 * @param {String} stlText ASCII STL content
 * @param {Number} offset Translation amount applied along merged vertex normals
 * @returns {Object} Structured, JSON-serializable audit report
 */
export const auditOffsetSTL = (stlText, offset) => {
  const numericOffset = Number(offset);
  const checks = [];
  const parsedFaces = parseASCIIStl(stlText);

  if (parsedFaces.length === 0) {
    return {
      type: OFFSET_AUDIT_TYPE,
      offset: numericOffset,
      faceCount: 0,
      vertexCount: 0,
      uniqueVertexCount: 0,
      mergedGroupCount: 0,
      faces: [],
      vertices: [],
      checks: [check("stl-contains-facets", false, "The input text does not contain any solid/facet block, so there is no geometry to offset.")],
    };
  }

  checks.push(check("stl-contains-facets", true, ""));

  // Merge identical coordinates (offsetObject compare + tempList grouping).
  // Every occurrence keeps a reference to its face normal for the normals sum.
  const groups = new Map();
  parsedFaces.forEach((face, faceIndex) => {
    face.vertices.forEach((vertex, vertexPositionInFace) => {
      const key = vertexKey(vertex);
      if (!groups.has(key)) {
        groups.set(key, {
          key,
          original: vertex,
          occurrences: [],
          normalsSum: [0, 0, 0],
        });
      }
      const group = groups.get(key);
      group.occurrences.push({ faceIndex, vertexPositionInFace });
      group.normalsSum[0] = nz(group.normalsSum[0] + (face.originalNormal[0] || 0));
      group.normalsSum[1] = nz(group.normalsSum[1] + (face.originalNormal[1] || 0));
      group.normalsSum[2] = nz(group.normalsSum[2] + (face.originalNormal[2] || 0));
    });
  });

  const vertices = [];
  const keyToNewPosition = new Map();

  Array.from(groups.values()).forEach((group, index) => {
    const normalized = normalizeOrZero(group.normalsSum);
    const direction = normalized.vector;
    // offsetObject.calcNewPosition: offset * normal + vertex
    const newCoordinates = nzArray([
      numericOffset * direction[0] + group.original[0],
      numericOffset * direction[1] + group.original[1],
      numericOffset * direction[2] + group.original[2],
    ]);
    keyToNewPosition.set(group.key, newCoordinates);

    const delta = nzArray([newCoordinates[0] - group.original[0], newCoordinates[1] - group.original[1], newCoordinates[2] - group.original[2]]);
    const displacementLength = nz(Math.sqrt(delta[0] * delta[0] + delta[1] * delta[1] + delta[2] * delta[2]));

    vertices.push({
      index,
      key: group.key,
      originalCoordinates: group.original,
      occurrenceCount: group.occurrences.length,
      merged: group.occurrences.length > 1,
      occurrences: group.occurrences,
      normalsSum: group.normalsSum,
      offsetDirection: direction,
      directionDegenerate: normalized.degenerate,
      newCoordinates,
      displacementLength,
    });
  });

  // Rebuild faces with their new vertices and recomputed normals.
  const faces = parsedFaces.map((face, faceIndex) => {
    const newVertices = face.vertices.map((vertex) => keyToNewPosition.get(vertexKey(vertex)));
    const recomputedNormal = calculateFaceNormal(newVertices[0], newVertices[1], newVertices[2]);
    return {
      index: faceIndex,
      originalNormal: face.originalNormal,
      recomputedNormal,
      originalVertices: face.vertices,
      newVertices,
      vertexKeys: face.vertices.map(vertexKey),
    };
  });

  // Check 1: displacement length must equal |offset| (tolerance 1e-6)
  vertices.forEach((vertex) => {
    const expectedLength = Math.abs(numericOffset);
    checks.push(
      check(
        `vertex-${vertex.index}-displacement-length-equals-offset`,
        Math.abs(vertex.displacementLength - expectedLength) <= OFFSET_EPSILON,
        `Vertex ${vertex.index} displacement length ${vertex.displacementLength} does not equal |offset| ${expectedLength}.`,
      ),
    );
  });

  // Check 2: recomputed normals must be unit vectors
  faces.forEach((face) => {
    const normalLength = length3({ x: face.recomputedNormal[0], y: face.recomputedNormal[1], z: face.recomputedNormal[2] });
    checks.push(
      check(
        `face-${face.index}-recomputed-normal-is-unit`,
        Math.abs(normalLength - 1) <= OFFSET_EPSILON,
        `Face ${face.index} recomputed normal length is ${normalLength}, expected 1.`,
      ),
    );
  });

  // Check 3: zero offset must leave every coordinate exactly unchanged
  if (numericOffset === 0) {
    vertices.forEach((vertex) => {
      const identical = vertex.newCoordinates.every((value, component) => value === vertex.originalCoordinates[component]);
      checks.push(
        check(
          `vertex-${vertex.index}-zero-offset-keeps-coordinates`,
          identical,
          `Vertex ${vertex.index} moved even though the offset is 0: ${JSON.stringify(vertex.originalCoordinates)} -> ${JSON.stringify(
            vertex.newCoordinates,
          )}.`,
        ),
      );
    });
  }

  const vertexCount = parsedFaces.reduce((total, face) => total + face.vertices.length, 0);
  const mergedGroupCount = vertices.filter((vertex) => vertex.merged).length;

  return {
    type: OFFSET_AUDIT_TYPE,
    offset: numericOffset,
    faceCount: faces.length,
    vertexCount,
    uniqueVertexCount: vertices.length,
    mergedGroupCount,
    faces,
    vertices,
    checks,
  };
};

export default {
  auditClippingSnapshot,
  auditOffsetSTL,
};
